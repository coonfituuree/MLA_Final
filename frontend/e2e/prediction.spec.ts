test('new fitted classifiers work through the real interface', async ({ page }) => {
  await page.goto('/')
  await expect(page.getByText('Local models ready')).toBeVisible()
  await page.getByLabel('Job description').fill(data.description)
  for (const [model, score] of Object.entries(data.optional_model_scores ?? {})) {
    await page.getByLabel('Analysis model').selectOption(model)
    const waiting = page.waitForResponse(r => r.url().endsWith('/api/v1/predictions') && r.request().method() === 'POST')
    await page.getByRole('button', { name: 'Analyze advertisement' }).click()
    const result = await (await waiting).json()
    expect(result.model_name).toBe(model)
    expect(result.model_score).toBeCloseTo(Number(score), 6)
    expect(result.comparisons.map((m: {model_name: string}) => m.model_name)).toContain(model)
  }
})
