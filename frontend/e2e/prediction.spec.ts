test('real prediction, model selection, validation, file upload and mobile layout', async ({ page, request }) => {
  const errors: string[] = []
  page.on('pageerror', e => errors.push(e.message))
  await page.goto('/')
  await expect(page.getByText('Local models ready')).toBeVisible()
  await page.getByLabel('Job description', { exact: false }).fill(data.description)
  let waiting = page.waitForResponse(r => r.url().endsWith('/api/v1/predictions') && r.request().method() === 'POST')
  await page.getByRole('button', { name: 'Analyze advertisement' }).click()
  let result = await (await waiting).json()
  expect(result.model_name).toBe('neural_network')
  expect(result.model_score).toBeCloseTo(data.neural_score, 6)
  await expect(page.getByTestId('learned-classification')).toContainText(result.predicted_label ? 'Potentially fraudulent' : 'Predicted legitimate')
  await page.getByLabel('Analysis model').selectOption('logistic_regression')
  await expect(page.getByText('Input or model changed.')).toBeVisible()
  waiting = page.waitForResponse(r => r.url().endsWith('/api/v1/predictions') && r.request().method() === 'POST')
  await page.getByRole('button', { name: 'Analyze advertisement' }).click()
  result = await (await waiting).json()
  expect(result.model_score).toBeCloseTo(data.logistic_score, 6)
  await page.getByLabel('Job description').fill('<p> </p>')
  await page.getByRole('button', { name: 'Analyze advertisement' }).click()
  await expect(page.getByRole('alert')).toContainText('readable text')
  await page.getByRole('button', { name: 'Upload .txt file' }).click()
  await page.locator('#file').setInputFiles({ name: 'heldout-vacancy.txt', mimeType: 'text/plain', buffer: Buffer.from(data.description) })
  waiting = page.waitForResponse(r => r.url().endsWith('/api/v1/predictions/file'))
  await page.getByRole('button', { name: 'Analyze advertisement' }).click()
  result = await (await waiting).json()
  expect(result.model_score).toBeCloseTo(data.logistic_score, 6)
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy()
  await page.screenshot({ path: '../reports/improvements/application-mobile.png', fullPage: true })
  expect(errors).toEqual([])
  expect((await request.get('/api/ready')).ok()).toBeTruthy()
})

test('latest complete fields, contextual evidence and paired equipment control', async ({ page }) => {
  await page.goto('/')
  await expect(page.getByText('Local models ready')).toBeVisible()
  await page.getByLabel('Job title').fill(equipment.fields.title)
  await page.getByLabel('Job description').fill(equipment.fields.description)
  await page.getByText('Add more context', { exact: false }).click()
  await page.getByLabel('Company profile').fill(equipment.fields.company_profile)
  await page.getByLabel('Requirements', { exact: false }).fill(equipment.fields.requirements)
  await page.getByLabel('Benefits', { exact: false }).fill(equipment.fields.benefits)
  let waiting = page.waitForResponse(r => r.url().endsWith('/api/v1/predictions') && r.request().method() === 'POST')
  await page.getByRole('button', { name: 'Analyze advertisement' }).click()
  let response = await waiting
  const sent = response.request().postDataJSON()
  for (const [key,value] of Object.entries(equipment.fields)) expect(sent[key]).toBe(value)
  let result = await response.json()
  expect(result.input_summary.prepared_sha256).toBe(equipment.prepared_sha256)
  expect(result.review.signals.map((s: {code: string}) => s.code)).toContain('candidate_funded_equipment')
  await expect(page.getByRole('heading', { name: 'Additional review recommended', exact: true })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Candidate-funded equipment arrangement' })).toBeVisible()
  await expect(page.locator('blockquote')).toContainText('initially covered by the candidate')
  await page.screenshot({ path: '../reports/improvements/application-equipment.png', fullPage: true })
  await page.getByLabel('Requirements', { exact: false }).fill(equipment.free_requirements)
  waiting = page.waitForResponse(r => r.url().endsWith('/api/v1/predictions') && r.request().method() === 'POST')
  await page.getByRole('button', { name: 'Analyze advertisement' }).click()
  result = await (await waiting).json()
  expect(result.review.signals).toEqual([])
  // A clear control for negation and ordinary remote/courier duties.
  await page.getByLabel('Job description').fill('Entry-level remote administrative role. Employer equipment is provided at no cost. No payment is required. Couriers deliver documented orders using normal safety procedures.')
  await page.getByLabel('Requirements', { exact: false }).fill('No experience required.')
  waiting = page.waitForResponse(r => r.url().endsWith('/api/v1/predictions') && r.request().method() === 'POST')
  await page.getByRole('button', { name: 'Analyze advertisement' }).click()
  result = await (await waiting).json()
  expect(result.review.signals).toEqual([])
})

